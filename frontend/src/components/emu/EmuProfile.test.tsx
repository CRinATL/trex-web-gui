import { act, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import * as api from '../../api'
import type { EmuMsg, EmuNamespace, EmuProfileInspected } from '../../api'
import { emuStore } from '../../emuStore'
import emuMsg from '../../__fixtures__/emuMsg.json'
import { EmuProfile } from './EmuProfile'

const connected = emuMsg.connected as EmuMsg
const loadedMsg = emuMsg.loaded as EmuMsg
const loading = emuMsg.loading as EmuMsg

const ns = (vport: number, clients: number, ours: boolean): EmuNamespace => ({ vport, tci: [0, 0], tpid: [0, 0], active_clients: clients, plug_names: [], ours })
const listing = (namespaces: EmuNamespace[], interrupted = false) => ({ generation: 0, namespaces, interrupted })
const inspected: EmuProfileInspected = {
  tunables: [], counts: { namespaces: 2, clients: 6 }, plugins: ['arp', 'icmp'], vports: [0, 1], warnings: ['vport 1 is not a port of the connected TRex, which has 1'],
}

beforeEach(() => { act(() => emuStore.push(connected)) })
afterEach(() => vi.restoreAllMocks())

async function typePath(user: ReturnType<typeof userEvent.setup>) {
  await user.type(screen.getByLabelText(/^EMU profile/), '/p/two.py')
}

describe('EmuProfile', () => {
  it('Inspect shows the counts, plugins, vports and warnings', async () => {
    const user = userEvent.setup()
    const insp = vi.spyOn(api, 'emuProfileInspect').mockResolvedValue(inspected)
    render(<EmuProfile />)
    expect(screen.getByRole('button', { name: 'Inspect' })).toBeDisabled()
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Inspect' }))
    expect(insp).toHaveBeenCalledWith('/p/two.py', [])
    expect(await screen.findByText(/2 namespace\(s\), 6 client\(s\); plugins: arp, icmp; vports: 0, 1/)).toBeInTheDocument()
    expect(screen.getByText(/vport 1 is not a port/)).toBeInTheDocument()
  })
  it('Browse… lists only .py files, which is all the backend takes', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'fsList').mockResolvedValue({ path: '/opt/trex/v3.08/emu', parent: '/opt/trex/v3.08', truncated: false, entries: [
      { name: 'simple_emu.py', dir: false, size: 2900 }, { name: 'ipfix_dnac_scale_test.cfg', dir: false, size: 900 },
      { name: 'stream.yaml', dir: false, size: 10 }] })
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Browse…' }))
    const dialog = await screen.findByRole('dialog', { name: 'Pick an EMU profile (.py)' })
    await within(dialog).findByRole('button', { name: 'simple_emu.py' })
    expect(within(dialog).queryByRole('button', { name: 'stream.yaml' })).toBeNull()
  })
  it('shows a profile error from Inspect', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuProfileInspect').mockRejectedValue(new api.ApiError(422, 'profile_error', 'no such profile'))
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Inspect' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('no such profile')
  })
  it('Load names the target and what the server holds, and sends confirm only when nothing is foreign', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(0, 3, true)]))
    const load = vi.spyOn(api, 'emuProfileLoad').mockResolvedValue(loadedMsg)
    render(<EmuProfile />)
    await typePath(user)
    await user.type(screen.getByLabelText(/^Rate limit/), '500')
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    const dlg = await screen.findByRole('dialog', { name: 'Load the profile' })
    expect(dlg).toHaveTextContent('/p/two.py onto 127.0.0.1:4510')
    expect(await within(dlg).findByText(/On the server now: 1 namespace\(s\), 3 client\(s\)\./)).toBeInTheDocument()
    expect(within(dlg).queryByRole('checkbox')).toBeNull()
    await user.click(within(dlg).getByRole('button', { name: 'Load' }))
    expect(load).toHaveBeenCalledWith('/p/two.py', [], { confirm: true, foreign_ack: false, max_rate: 500 })
    await vi.waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect(emuStore.get()).toBe(loadedMsg)
  })
  it('foreign namespaces show their count and a checkbox; without the tick nothing is sent, with it foreign_ack is', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(0, 3, true), ns(1, 4, false)]))
    const load = vi.spyOn(api, 'emuProfileLoad').mockResolvedValue(loadedMsg)
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    const dlg = await screen.findByRole('dialog')
    expect(await within(dlg).findByText(/2 namespace\(s\), 7 client\(s\), of which 1 namespace\(s\) with 4 client\(s\) were not added by this app/)).toBeInTheDocument()
    await user.click(within(dlg).getByRole('button', { name: 'Load' }))
    expect(load).not.toHaveBeenCalled()
    expect(await within(dlg).findByRole('alert')).toHaveTextContent('Tick the box')
    await user.click(within(dlg).getByRole('checkbox'))
    await user.click(within(dlg).getByRole('button', { name: 'Load' }))
    expect(load).toHaveBeenCalledWith('/p/two.py', [], { confirm: true, foreign_ack: true })
  })
  it('a foreign_namespaces refusal shows its message and offers the tick with wording that claims no count', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(0, 3, true)]))
    const load = vi.spyOn(api, 'emuProfileLoad')
      .mockRejectedValueOnce(new api.ApiError(409, 'foreign_namespaces', 'Another EMU client kept changing the namespaces'))
      .mockResolvedValue(loadedMsg)
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    const dlg = await screen.findByRole('dialog')
    await within(dlg).findByText(/On the server now/)
    await user.click(within(dlg).getByRole('button', { name: 'Load' }))
    expect(await within(dlg).findByRole('alert')).toHaveTextContent('Another EMU client kept changing')
    const box = within(dlg).getByRole('checkbox', { name: /did not add, or another client was changing it during the check/ })
    await user.click(box)
    await user.click(within(dlg).getByRole('button', { name: 'Load' }))
    expect(load).toHaveBeenLastCalledWith('/p/two.py', [], { confirm: true, foreign_ack: true })
  })
  it('Remove needs the confirm, which names the target, and sends confirm:true', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    const remove = vi.spyOn(api, 'emuProfileRemove').mockResolvedValue(connected)
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    expect(remove).not.toHaveBeenCalled()
    const dlg = await screen.findByRole('dialog', { name: 'Remove everything' })
    expect(dlg).toHaveTextContent('from 127.0.0.1:4510')
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).toHaveBeenCalledWith({ confirm: true, foreign_ack: false })
  })
  it('Cancel sends nothing', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    const remove = vi.spyOn(api, 'emuProfileRemove')
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Cancel' }))
    expect(remove).not.toHaveBeenCalled()
    expect(screen.queryByRole('dialog')).toBeNull()
  })
  it('disables both writes while busy and leaves the progress to the status line above it', () => {
    act(() => emuStore.push(loading))
    render(<EmuProfile />)
    expect(screen.queryByText(/loading: 3/)).toBeNull()       // EmuStatus shows "loading: 3 of 6" on the same page
    expect(screen.getByRole('button', { name: 'Load…' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Remove all…' })).toBeDisabled()
  })
  it('an interrupted listing says it may be incomplete and offers the tick before any refusal', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(0, 3, true)], true))
    const remove = vi.spyOn(api, 'emuProfileRemove').mockResolvedValue(connected)
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    const dlg = await screen.findByRole('dialog', { name: 'Remove everything' })
    expect(await within(dlg).findByText(/may be incomplete/)).toBeInTheDocument()
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).not.toHaveBeenCalled()
    await user.click(within(dlg).getByRole('checkbox', { name: /did not add, or another client was changing it/ }))
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).toHaveBeenCalledWith({ confirm: true, foreign_ack: true })
  })
  it('a listing that fails says the server could not be read', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockRejectedValue(new api.ApiError(502, 'unreachable', 'no reply'))
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    const dlg = await screen.findByRole('dialog', { name: 'Remove everything' })
    expect(await within(dlg).findByText('Could not read what the server holds: no reply')).toBeInTheDocument()
  })
  it('Remove counts the foreign namespaces and needs the tick to send foreign_ack', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(0, 2, true), ns(1, 4, false)]))
    const remove = vi.spyOn(api, 'emuProfileRemove').mockResolvedValue(connected)
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    const dlg = await screen.findByRole('dialog', { name: 'Remove everything' })
    expect(await within(dlg).findByText(/2 namespace\(s\), 6 client\(s\), of which 1 namespace\(s\) with 4 client\(s\) were not added by this app/)).toBeInTheDocument()
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).not.toHaveBeenCalled()
    await user.click(within(dlg).getByRole('checkbox', { name: 'Remove the namespaces this app did not add as well' }))
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).toHaveBeenCalledWith({ confirm: true, foreign_ack: true })
  })
  it('a write error goes when the profile path changes', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    vi.spyOn(api, 'emuProfileLoad').mockRejectedValue(new api.ApiError(400, 'emu_error', 'the server refused'))
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Load' }))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cancel' }))
    expect(await screen.findByText(/the server refused/)).toBeInTheDocument()
    await user.type(screen.getByLabelText(/^EMU profile/), 'x')
    expect(screen.queryByText(/the server refused/)).toBeNull()
  })
  it('the writes are off while not connected', () => {
    act(() => emuStore.push(emuMsg.disconnected as EmuMsg))
    render(<EmuProfile />)
    expect(screen.getByRole('button', { name: 'Remove all…' })).toBeDisabled()
  })
  it('a failed write shows the server text with how far it got, and a partial profile is flagged', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    vi.spyOn(api, 'emuProfileLoad').mockRejectedValue(new api.ApiError(502, 'unreachable', 'lost the connection; removed 1; added 2 of 6 clients'))
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    const dlg = await screen.findByRole('dialog')
    await user.click(within(dlg).getByRole('button', { name: 'Load' }))
    expect(await within(dlg).findByRole('alert')).toHaveTextContent('lost the connection; removed 1; added 2 of 6 clients')
    await user.click(within(dlg).getByRole('button', { name: 'Cancel' }))
    expect(screen.getByRole('alert')).toHaveTextContent('added 2 of 6 clients')
    act(() => emuStore.push({ ...loadedMsg, loaded: { ...loadedMsg.loaded!, partial: true } }))
    expect(screen.getByText(/A partial profile is on the server/)).toBeInTheDocument()
  })
  it('a crash_risk refusal shows its message and a tick; crash_ack goes only when ticked and resets when the dialog reopens', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(1, 4, false)]))
    const remove = vi.spyOn(api, 'emuProfileRemove')
      .mockRejectedValueOnce(new api.ApiError(409, 'crash_risk', 'Removing 1 namespace(s) will crash the EMU server'))
      .mockResolvedValue(connected)
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    let dlg = await screen.findByRole('dialog')
    await within(dlg).findByText(/On the server now/)
    expect(within(dlg).queryByRole('checkbox', { name: /Remove anyway/ })).toBeNull()
    await user.click(within(dlg).getByRole('checkbox'))
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).toHaveBeenLastCalledWith({ confirm: true, foreign_ack: true })
    expect(await within(dlg).findByRole('alert')).toHaveTextContent('will crash the EMU server')
    const box = within(dlg).getByRole('checkbox', { name: 'Remove anyway: the EMU server will crash and must be restarted' })
    await user.click(box)
    await user.click(within(dlg).getByRole('button', { name: 'Cancel' }))
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    dlg = await screen.findByRole('dialog')
    await within(dlg).findByText(/On the server now/)
    expect(within(dlg).queryByRole('checkbox', { name: /Remove anyway/ })).toBeNull()
  })
  it('crash_ack: true is sent after the tick', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([ns(1, 4, false)]))
    const remove = vi.spyOn(api, 'emuProfileRemove')
      .mockRejectedValueOnce(new api.ApiError(409, 'crash_risk', 'will crash'))
      .mockResolvedValue(connected)
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    const dlg = await screen.findByRole('dialog')
    await within(dlg).findByText(/On the server now/)
    await user.click(within(dlg).getByRole('checkbox'))
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    await user.click(await within(dlg).findByRole('checkbox', { name: /Remove anyway/ }))
    await user.click(within(dlg).getByRole('button', { name: 'Remove' }))
    expect(remove).toHaveBeenLastCalledWith({ confirm: true, foreign_ack: true, crash_ack: true })
  })
  it('the Load confirm warns that a profile can start sending traffic at once', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    expect(await screen.findByRole('dialog', { name: 'Load the profile' })).toHaveTextContent(/can start sending traffic on its ports at once.*DHCP server plugin.*starve a network/)
  })
  it('an Inspect reply for a path that is no longer the current one is dropped, and Load sends the new path with no tunables', async () => {
    const user = userEvent.setup()
    let late: (v: EmuProfileInspected) => void = () => {}
    vi.spyOn(api, 'emuProfileInspect').mockReturnValue(new Promise((res) => { late = res }))
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    const load = vi.spyOn(api, 'emuProfileLoad').mockResolvedValue(loadedMsg)
    render(<EmuProfile />)
    await typePath(user)
    await user.click(screen.getByRole('button', { name: 'Inspect' }))
    const input = screen.getByLabelText(/^EMU profile/)
    await user.clear(input)
    await user.type(input, '/p/b.py')
    await act(async () => { late({ ...inspected, tunables: [{ name: 'clients', type: 'int', default: 9, help: '' } as never], counts: { namespaces: 7, clients: 77 } }) })
    expect(screen.queryByText(/7 namespace\(s\), 77 client\(s\)/)).toBeNull()
    expect(screen.getByRole('button', { name: 'Inspect' })).toBeEnabled()
    await user.click(screen.getByRole('button', { name: 'Load…' }))
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Load' }))
    expect(load).toHaveBeenCalledWith('/p/b.py', [], { confirm: true, foreign_ack: false })
  })
  it('a failed removal says the last removal did not finish, a failed load the last load', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    vi.spyOn(api, 'emuProfileRemove').mockRejectedValue(new api.ApiError(400, 'emu_error', 'removed 1 of 2 namespaces'))
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Remove' }))
    await user.click(await screen.findByRole('button', { name: 'Cancel' }))
    act(() => emuStore.push({ ...loadedMsg, loaded: { ...loadedMsg.loaded!, partial: true } }))
    expect(screen.getByText(/A partial profile is on the server: the last removal did not finish/)).toBeInTheDocument()
    expect(screen.queryByText(/the last load/)).toBeNull()
  })
  it('a refused removal (409, nothing sent) does not relabel a partial profile as the last removal', async () => {
    const user = userEvent.setup()
    vi.spyOn(api, 'emuNamespaces').mockResolvedValue(listing([]))
    vi.spyOn(api, 'emuProfileRemove').mockRejectedValue(new api.ApiError(409, 'busy', 'another EMU operation is in progress'))
    render(<EmuProfile />)
    await user.click(screen.getByRole('button', { name: 'Remove all…' }))
    await user.click(within(await screen.findByRole('dialog')).getByRole('button', { name: 'Remove' }))
    await user.click(await screen.findByRole('button', { name: 'Cancel' }))
    act(() => emuStore.push({ ...loadedMsg, loaded: { ...loadedMsg.loaded!, partial: true } }))
    expect(screen.getByText(/A partial profile is on the server: a load or removal did not finish/)).toBeInTheDocument()
    expect(screen.queryByText(/the last removal/)).toBeNull()
  })
  it('an out-of-range rate limit disables the writes', async () => {
    const user = userEvent.setup()
    render(<EmuProfile />)
    await user.type(screen.getByLabelText(/^Rate limit/), '0')
    expect(screen.getByRole('button', { name: 'Remove all…' })).toBeDisabled()
  })
})
