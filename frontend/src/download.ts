// Hands a Blob to the browser as a file download through a temporary <a download>.
export function downloadBlob(name: string, blob: Blob): void {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = name
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 0)   // some browsers cancel a download whose URL is revoked before it starts
}
