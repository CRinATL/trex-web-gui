  it('a settings message that arrives before the first GET resolves wins over the older GET', async () => {
    let resolve!: (r: api.SettingsReply) => void
    vi.spyOn(api, 'getSettings').mockReturnValue(new Promise((r) => { resolve = r }))
    const send = renderLive()
    await section('Files on the backend host')
    send({ type: 'settings', settings: { ...settings('imported'), preferences: { ...PREFS, wireshark_path: '/opt/ws' } }, load_error: null, data_dir: '/d' })
    await act(async () => { resolve({ settings: settings('lab'), load_error: null, data_dir: '/d' }) })
    expect(await screen.findByLabelText('Wireshark path')).toHaveValue('/opt/ws')
  })
