#!/usr/bin/env python3
"""The v1.0 parity checklist: docs/parity-v1.0.md, generated from trex-rework's inventory and checked.

  parity.py sync  --plans DIR           regenerate ID, Feature, Phase and Status; keep each row's Evidence
  parity.py check --plans DIR [--gate]  report mode (exit 0 unless the doc is stale or cites a missing path);
                                        --gate also fails on any `?` status (empty evidence is counted, not
                                        failed: a row may list a feature before its evidence is written)

The rows are the inventory's own parity bar (plans/inventory-merged.md, "Counts and parity bar"): an A, B or C
row whose verdict starts with Keep, Keep+, Replace or New and whose phase cell starts with P1-P6. TREX_PLANS
(Makefile) names the inventory directory; this script never writes there."""
import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = "docs/parity-v1.0.md"
INVENTORY = "inventory-merged.md"
ID = re.compile(r"[ABC][0-9]+(\.[0-9]+)?")
VERDICT = re.compile(r"(Keep|Keep\+|Replace|New)")
PHASE = re.compile(r"P[1-6]")
CELL_SPLIT = re.compile(r"(?<!\\)\|")
TICKS = re.compile(r"`([^`]+)`")
LEDGER = re.compile(r'(\S+\.md:\d+(?:-\d+)?)\s+"[^"]*"')
VITEST = re.compile(r'(\S+\.test\.tsx?) "([^"]+)"')
RC1_USE = re.compile(r"rc1 use\b")
LOCATION = re.compile(r"(::\S*|:\d+(?:-\d+)?)$")
DOC_HEAD = "| ID | Feature | Phase | Status | Evidence |"
HEADER = """# v1.0 parity checklist

Generated by `make parity-sync` from the TRex GUI rework inventory; do not edit the ID, Feature, Phase and
Status columns (a sync overwrites them). Fill the Evidence cell by hand. `make parity` reports the gaps and
checks that every cited path exists; `make parity PARITY_GATE=1` fails while any row is `?`. An empty
Evidence cell is counted, not failed.

An Evidence cell holds one or more of:

- a real-tier or unit test in backticks, path then `::` then the test name, under `tests/`;
- a ledger line with a snippet, the file, a colon, the line number, a space and the quoted text from that
  line, written without backticks so that `make citations` checks the snippet;
- a screenshot in backticks, under `docs/gui-inventory/screens/`;
- a vitest test in backticks, path then a space and the quoted `it()` title (the check looks for the title in
  the file), for example `frontend/src/state.test.ts "caps the log at 2000 and rpc at 500"`;
- rc1 use, YYYY-MM-DD (written as plain text, as shown) for a feature used during the rc1 week.

Write a literal `|` inside a cell as `\\|`; a row with an unescaped one is reported as malformed.

"""


class ParityError(Exception):
    """The doc holds a row the inventory no longer has, or the inventory is unreadable."""


@dataclass(frozen=True)
class Row:
    """One parity row; status is the inventory's first word: built, partial or ?."""

    id: str
    feature: str
    verdict: str
    phase: str
    status: str


def cells(line: str) -> list[str]:
    """Splits a Markdown table line into stripped cells, honouring `\\|`."""
    return [c.strip() for c in CELL_SPLIT.split(line.strip())[1:-1]]


def parity_rows(inventory_text: str) -> list[Row]:
    """Returns the inventory's parity rows, finding columns by header name in every table that has them."""
    rows: list[Row] = []
    cols: dict[str, int] | None = None
    for line in inventory_text.splitlines():
        if not line.startswith("|"):
            cols = None
            continue
        parts = cells(line)
        if parts and parts[0] == "ID":
            cols = {name: i for i, name in enumerate(parts)}
            if not {"Verdict", "Phase", "Status"} <= cols.keys():
                cols = None
            continue
        if cols is None or len(parts) < len(cols) or not ID.fullmatch(parts[0]):
            continue
        verdict, phase = parts[cols["Verdict"]], parts[cols["Phase"]]
        if not (VERDICT.match(verdict) and PHASE.match(phase)):
            continue
        feature = parts[cols.get("Feature", cols.get("Capability", 1))]
        status = (parts[cols["Status"]].split() or [""])[0]
        rows.append(Row(parts[0], feature, verdict, phase, status))
    return rows


def doc_evidence(doc_text: str) -> dict[str, tuple[str, str, str, str]]:
    """Returns {id: (feature, phase, status, evidence)} for the doc's table rows."""
    out: dict[str, tuple[str, str, str, str]] = {}
    for line in doc_text.splitlines():
        parts = cells(line) if line.startswith("|") else []
        if len(parts) == 5 and ID.fullmatch(parts[0]):
            out[parts[0]] = (parts[1], parts[2], parts[3], parts[4])
    return out


def malformed_rows(doc_text: str) -> list[str]:
    """Returns the IDs of table rows that do not split into five cells (an unescaped `|` in a cell)."""
    out: list[str] = []
    for line in doc_text.splitlines():
        parts = cells(line) if line.startswith("|") else []
        if parts and ID.fullmatch(parts[0]) and len(parts) != 5:
            out.append(parts[0])
    return out


def sync(inventory_text: str, doc_text: str | None) -> str:
    """Regenerates the doc from the inventory, keeping each ID's Evidence; refuses to drop a row."""
    rows = parity_rows(inventory_text)
    old = doc_evidence(doc_text) if doc_text else {}
    bad = malformed_rows(doc_text) if doc_text else []
    if bad:
        raise ParityError("malformed rows, so sync would drop their evidence: " + ", ".join(bad)
                          + " (escape | as \\|)")
    gone = sorted(set(old) - {r.id for r in rows})
    if gone:
        raise ParityError("rows in the doc but gone from the inventory: " + ", ".join(gone))
    lines = [DOC_HEAD, "|---|---|---|---|---|"]
    for r in rows:
        evidence = old.get(r.id, ("", "", "", ""))[3]
        lines.append(f"| {r.id} | {r.feature} | {r.phase} | {r.status} | {evidence} |")
    return HEADER + "\n".join(lines) + "\n"


def evidence_paths(evidence: str) -> list[str]:
    """Returns the file paths an Evidence cell cites: backticked spans and unbackticked ledger lines."""
    spans = [t for t in TICKS.findall(evidence) if not RC1_USE.match(t)]
    spans += LEDGER.findall(TICKS.sub("", evidence))
    paths = []
    for s in spans:
        m = VITEST.fullmatch(s.strip())
        paths.append(m[1] if m else LOCATION.sub("", s.strip()))
    return paths


def vitest_titles(evidence: str) -> list[tuple[str, str]]:
    """Returns (path, title) for each vitest form in an Evidence cell."""
    return [m.groups() for t in TICKS.findall(evidence) if (m := VITEST.fullmatch(t.strip()))]


def check(inventory_text: str, doc_text: str, gate: bool, root: Path) -> tuple[int, list[str]]:
    """Compares the doc with the inventory; returns (exit code, output lines)."""
    rows = parity_rows(inventory_text)
    doc = doc_evidence(doc_text)
    problems: list[str] = []
    bad = set(malformed_rows(doc_text))
    problems += [f"{i}: malformed row (escape | as \\|)" for i in sorted(bad)]
    for r in rows:
        if r.id not in doc and r.id in bad:
            continue
        if r.id not in doc or doc[r.id][2] != r.status:
            problems.append(f"{r.id}: stale: run make parity-sync")
    known = {r.id for r in rows}
    problems += [f"{i}: stale: run make parity-sync (not in the inventory)" for i in sorted(set(doc) - known)]
    bare: list[str] = []
    for r in rows:
        evidence = doc.get(r.id, ("", "", "", ""))[3]
        if not evidence:
            bare.append(r.id)
        problems += [f"{r.id}: evidence path does not exist: {p}" for p in evidence_paths(evidence)
                     if not (root / p).exists()]
        problems += [f'{r.id}: vitest title not found in {p}: "{t}"' for p, t in vitest_titles(evidence)
                     if (root / p).is_file() and t not in (root / p).read_text()]
    count = {s: sum(r.status == s for r in rows) for s in ("built", "partial", "?")}
    lines = [f"{len(rows)} parity rows; {count['built']} built, {count['partial']} partial, {count['?']} ?; "
             f"{len(bare)} without evidence", *bare]
    if gate:
        problems += [f"{r.id}: status is ?" for r in rows if r.status == "?"]
    return (1 if problems else 0), lines + problems


def main(argv: list[str]) -> int:
    """Runs sync or check against the inventory under --plans; exit 2 when the inventory is missing."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("mode", choices=["sync", "check"])
    ap.add_argument("--plans", required=True, type=Path)
    ap.add_argument("--gate", action="store_true")
    args = ap.parse_args(argv)
    inv = args.plans / INVENTORY
    if not inv.is_file():
        print(f"parity: {inv} not found; set TREX_PLANS to trex-rework's plans directory", file=sys.stderr)
        return 2
    inventory_text = inv.read_text()
    doc = ROOT / DOC
    doc_text = doc.read_text() if doc.exists() else None
    if args.mode == "sync":
        try:
            doc.write_text(sync(inventory_text, doc_text))
        except ParityError as e:
            print(f"parity: {e}", file=sys.stderr)
            return 1
        return 0
    if doc_text is None:
        print(f"parity: {DOC} is missing: run make parity-sync", file=sys.stderr)
        return 1
    rc, lines = check(inventory_text, doc_text, args.gate, ROOT)
    print("\n".join(lines))
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
